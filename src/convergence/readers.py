"""k8s/admin/secret-readers.yaml, from the service list: one RoleBinding per namespace a
deploy service's units use, and the engine's own.

    python -m convergence secret-readers ../release-state/state.json .. > k8s/admin/secret-readers.yaml

Each service's pubrules.json is read from a checkout beside the others (`..`, as on a
laptop); its deploy block's namespace and every unit's are the namespaces.
"""

from __future__ import annotations

import json
from pathlib import Path

from .state import services
from .walker import CONFIG

OWN = "convergence"
HEAD = """# Generated by `python -m convergence secret-readers STATE.json CHECKOUTS`: do not edit.
# The namespaces whose Secrets the engine may read, for the k8s.secret and
# k8s.secrets-declared checks (key names and value lengths, never a value shown): every
# deploy service's units', and its own. kube-system and the rest stay out of reach.
"""
BINDING = """apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: convergence-secret-read
  namespace: {ns}
roleRef: {{apiGroup: rbac.authorization.k8s.io, kind: ClusterRole, name: convergence-secret-read}}
subjects: [{{kind: ServiceAccount, name: app, namespace: convergence}}]
"""


def namespaces(config: dict) -> list[str]:
    block = config.get("deploy") or {}
    found = [block["namespace"]] if block.get("namespace") else []
    units = block.get("units") or {}
    found += [u["namespace"] for u in (units.values() if isinstance(units, dict) else units)
              if isinstance(u, dict) and u.get("namespace")]
    return found


def deployed(state_text: str, checkouts: Path) -> set[str]:
    """Every namespace a deploy service's units use, from its pubrules.json beside the others."""
    found: set[str] = set()
    for slug in services(state_text):
        checkout = checkouts / slug.split("/")[1]
        path = checkout / CONFIG
        try:
            found.update(namespaces(json.loads(path.read_text(encoding="utf-8"))))
        except OSError:
            raise ValueError(f"{path} could not be read: check {slug} out beside the others") from None
    return found


def generate(state_text: str, checkouts: Path) -> str:
    return HEAD + "---\n".join(BINDING.format(ns=ns) for ns in sorted(deployed(state_text, checkouts) | {OWN}))


EXECUTORS_HEAD = """# Generated by `python -m convergence executor-accounts STATE.json CHECKOUTS`: do not edit.
# What a live run's Job walks as (jobs.py): in every deploy service's namespace but the
# engine's own, the ServiceAccount pubdeploy-executor, bound in that namespace alone to the
# reads a walk's checks make and the writes its fulfils make, as the engine's own
# (cluster-role.yaml, write-role.yaml), and to reading the namespaces themselves. Nothing
# else: no other delete, no exec, no RBAC, no namespace made. The credentials its walks
# need are the namespace's Secret pubdeploy-executor, which this file does not make.
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRole
metadata:
  name: pubdeploy-executor
rules:
  - apiGroups: [""]
    resources: [serviceaccounts, pods, pods/log, services, configmaps, events]
    verbs: [get, list]
  - apiGroups: [""]
    resources: [secrets]
    verbs: [get, list, create, update, patch]
  - apiGroups: [apps]
    resources: [deployments]
    verbs: [get, list, patch]
  - apiGroups: [apps]
    resources: [statefulsets, replicasets]
    verbs: [get, list]
  - apiGroups: [batch]
    resources: [cronjobs]
    verbs: [get, list]
  - apiGroups: [batch]
    resources: [jobs]
    verbs: [get, list, create, delete]
  - apiGroups: [networking.k8s.io]
    resources: [ingresses, networkpolicies]
    verbs: [get, list]
  - apiGroups: [rbac.authorization.k8s.io]
    resources: [roles, rolebindings]
    verbs: [get, list]
---
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRole
metadata:
  name: pubdeploy-executor-namespaces
rules:
  - apiGroups: [""]
    resources: [namespaces]
    verbs: [get, list]
"""
EXECUTOR = """---
apiVersion: v1
kind: ServiceAccount
metadata:
  name: pubdeploy-executor
  namespace: {ns}
---
apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: pubdeploy-executor
  namespace: {ns}
roleRef: {{apiGroup: rbac.authorization.k8s.io, kind: ClusterRole, name: pubdeploy-executor}}
subjects: [{{kind: ServiceAccount, name: pubdeploy-executor, namespace: {ns}}}]
"""


def executors(state_text: str, checkouts: Path) -> str:
    """k8s/admin/executor-accounts.yaml: the Job executor's accounts, one per namespace. The
    engine's own is left out: its admission policy refuses the engine's writes there."""
    found = sorted(deployed(state_text, checkouts) - {OWN})
    subjects = "".join(f"\n  - {{kind: ServiceAccount, name: pubdeploy-executor, namespace: {ns}}}" for ns in found)
    reads = ("---\napiVersion: rbac.authorization.k8s.io/v1\nkind: ClusterRoleBinding\nmetadata:\n"
             "  name: pubdeploy-executor-namespaces\nroleRef: {apiGroup: rbac.authorization.k8s.io, "
             f"kind: ClusterRole, name: pubdeploy-executor-namespaces}}\nsubjects:{subjects or ' []'}\n")
    return EXECUTORS_HEAD + "".join(EXECUTOR.format(ns=ns) for ns in found) + reads
