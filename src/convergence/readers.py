"""k8s/admin/secret-readers.yaml, from the service list: one RoleBinding per namespace a
deploy service's units use, and the engine's own.

    python -m convergence secret-readers ../release-state/state.json .. > k8s/admin/secret-readers.yaml

Each service's pubkit.json is read from a checkout beside the others (`..`, as on a
laptop); its deploy block's namespace and every unit's are the namespaces.
"""

from __future__ import annotations

import json
from pathlib import Path

from .state import services

OWN = "convergence"
HEAD = """# Generated by `python -m convergence secret-readers STATE.json CHECKOUTS`: do not edit.
# The namespaces whose Secrets the engine may read, for the k8s.secret and
# k8s.secrets-declared checks (key names and value lengths, never a value shown): every
# deploy service's units', and its own. kube-system and the rest stay out of reach.
"""
BINDING = """apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: convergence-secret-read
  namespace: {ns}
roleRef: {{apiGroup: rbac.authorization.k8s.io, kind: ClusterRole, name: convergence-secret-read}}
subjects: [{{kind: ServiceAccount, name: app, namespace: convergence}}]
"""


def namespaces(config: dict) -> list[str]:
    block = config.get("deploy") or {}
    found = [block["namespace"]] if block.get("namespace") else []
    units = block.get("units") or {}
    found += [u["namespace"] for u in (units.values() if isinstance(units, dict) else units)
              if isinstance(u, dict) and u.get("namespace")]
    return found


def generate(state_text: str, checkouts: Path) -> str:
    found = {OWN}
    for slug in services(state_text):
        path = checkouts / slug.split("/")[1] / "pubkit.json"
        try:
            found.update(namespaces(json.loads(path.read_text(encoding="utf-8"))))
        except OSError:
            raise ValueError(f"{path} could not be read: check {slug} out beside the others") from None
    return HEAD + "---\n".join(BINDING.format(ns=ns) for ns in sorted(found))
